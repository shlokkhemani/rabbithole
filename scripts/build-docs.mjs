import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createSnapshotProjection } from "../src/core/snapshot-projection.js";
import { buildSnapshotHtml } from "../src/core/snapshot-html.js";
import { toPersistedHole } from "../src/core/schema.js";
import { makeNode } from "../src/core/hole/node.js";
import { toolDefinitions } from "../src/node/mcp/tools.js";
import { getDompurifyScript, getMermaidScript, getUiAssets } from "../src/node/shared/dist-assets.js";
import { FETCH_PROXY_ALLOWED_HOSTS, WEB_CONNECT_SOURCES } from "../policy/origins.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const generatedDirectory = path.join(root, "docs/generated");
const check = process.argv.includes("--check");
const outputs = new Map();

const sourceFiles = await filesUnder("src", (name) => name.endsWith(".js") || name.endsWith(".d.ts"));
const testFiles = await filesUnder("test", (name) => name.endsWith(".test.mjs"));
const protects = await readTestPurposes(testFiles);
const packageJson = JSON.parse(await fs.readFile(path.join(root, "package.json"), "utf8"));
const tokenSource = await fs.readFile(path.join(root, "src/design/tokens.css"), "utf8");

outputs.set("module-map.md", moduleMap(sourceFiles));
outputs.set("test-map.md", testMap(protects));
outputs.set("tokens.md", tokenMap(tokenSource));
outputs.set("env.md", await envMap());
outputs.set("mcp-tools.md", mcpToolMap());
outputs.set("commands.md", commandMap(packageJson.scripts || {}));
outputs.set("csp.md", cspMap());
outputs.set("../tour.html", await buildTour());

const stale = [];
for (const [relativeName, contents] of outputs) {
  const target = path.resolve(generatedDirectory, relativeName);
  if (check) {
    const current = await fs.readFile(target, "utf8").catch(() => null);
    if (current !== contents) stale.push(path.relative(root, target));
  } else {
    await fs.mkdir(path.dirname(target), { recursive: true });
    await fs.writeFile(target, contents, "utf8");
  }
}

if (check) {
  const missingPaths = await scanDocumentPaths();
  if (stale.length || missingPaths.length) {
    if (stale.length) process.stderr.write(`Generated docs are stale:\n${stale.map((name) => `- ${name}`).join("\n")}\n`);
    if (missingPaths.length) process.stderr.write(`Document paths do not exist:\n${missingPaths.map((entry) => `- ${entry}`).join("\n")}\n`);
    process.exit(1);
  }
}

function heading(title) {
  return `<!-- Generated by scripts/build-docs.mjs. Do not edit. -->\n\n# ${title}\n\n`;
}

function moduleMap(files) {
  const groups = new Map();
  for (const file of files) {
    const parts = file.split("/");
    const group = parts.length > 2 ? `${parts[0]}/${parts[1]}` : parts[0];
    if (!groups.has(group)) groups.set(group, []);
    groups.get(group).push(file);
  }
  let out = heading("Module map");
  out += "This inventory is derived from the source tree.\n\n";
  for (const [group, entries] of [...groups].sort(([a], [b]) => a.localeCompare(b))) {
    out += `## ${group}\n\n${entries.map((file) => `- \`${file}\``).join("\n")}\n\n`;
  }
  return out;
}

function testMap(entries) {
  let out = heading("Test map");
  out += "Each description is harvested from the test file's `@protects` declaration.\n\n";
  for (const tier of ["contracts", "integration", "e2e", "performance", "packaging", "isolation-live"]) {
    const matches = entries.filter((entry) => entry.file.startsWith(`test/${tier}/`));
    out += `## ${tier}\n\n`;
    out += matches.length
      ? matches.map(({ file, purpose }) => `- \`${file}\` — ${purpose}`).join("\n") + "\n\n"
      : "_No tests in this tier._\n\n";
  }
  return out;
}

function tokenMap(source) {
  const tokens = [...source.matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/gi)]
    .map((match) => ({ name: match[1], value: match[2].trim() }));
  let out = heading("Design tokens");
  out += "Values are read from `src/design/tokens.css`; repeated theme overrides remain visible.\n\n";
  out += "| Token | Value |\n| --- | --- |\n";
  out += tokens.map(({ name, value }) => `| \`${name}\` | \`${value.replace(/\|/g, "\\|")}\` |`).join("\n");
  return out + "\n";
}

async function envMap() {
  const candidates = ["build.mjs", ...await filesUnder("src", (name) => name.endsWith(".js")), ...await filesUnder("scripts", (name) => name.endsWith(".mjs"))];
  const owners = new Map();
  for (const file of candidates) {
    const source = await fs.readFile(path.join(root, file), "utf8");
    for (const match of source.matchAll(/(?:process\.)?env\.([A-Z][A-Z0-9_]+)/g)) {
      if (!owners.has(match[1])) owners.set(match[1], new Set());
      owners.get(match[1]).add(file);
    }
  }
  let out = heading("Environment variables");
  out += "This is a usage inventory, not a promise that every variable is public configuration.\n\n";
  out += "| Variable | Read by |\n| --- | --- |\n";
  out += [...owners].sort(([a], [b]) => a.localeCompare(b))
    .map(([name, files]) => `| \`${name}\` | ${[...files].sort().map((file) => `\`${file}\``).join(", ")} |`).join("\n");
  return out + "\n";
}

function mcpToolMap() {
  let out = heading("MCP tools");
  for (const tool of toolDefinitions) {
    const summary = String(tool.description || "").split(/(?<=[.!?])\s/)[0];
    out += `## ${tool.name}\n\n${summary}\n\n`;
    const fields = Object.keys(tool.input || {});
    out += fields.length ? `Inputs: ${fields.map((field) => `\`${field}\``).join(", ")}\n\n` : "Inputs: none.\n\n";
  }
  return out;
}

function commandMap(scripts) {
  let out = heading("Commands");
  out += "| Command | Expansion |\n| --- | --- |\n";
  out += Object.entries(scripts).sort(([a], [b]) => a.localeCompare(b))
    .map(([name, command]) => `| \`npm run ${name}\` | \`${String(command).replace(/\|/g, "\\|")}\` |`).join("\n");
  return out + "\n";
}

function cspMap() {
  let out = heading("Network policy");
  out += "## Browser connect sources\n\n";
  out += WEB_CONNECT_SOURCES.map((source) => `- \`${source}\``).join("\n") + "\n\n";
  out += "The browser list is broad so users can choose custom model endpoints; script execution remains self-only.\n\n";
  out += "## Fetch-proxy hosts\n\n";
  out += FETCH_PROXY_ALLOWED_HOSTS.map((host) => `- \`${host}\``).join("\n") + "\n\n";
  out += "The proxy list is a separate server-side SSRF boundary and is intentionally narrow.\n";
  return out;
}

